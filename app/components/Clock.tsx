"use client";
// ["use client" とは何か / なぜ必要か]
// Next.js App Routerでは、コンポーネントはデフォルトで「Server Component」。
// Server Componentはサーバー上で1回だけ実行されてHTMLに変換され、
// ブラウザにはそのHTML結果だけが送られる。つまりブラウザ側で
// 再実行されることが無いので、useState（状態を持つ）や
// useEffect（ブラウザ上で副作用を起こす）は原理的に動作できない。
//
// このClockは「1秒ごとに表示を更新し続ける」必要がある＝
// ブラウザの中で時間経過とともに再描画され続ける必要がある。
// これはサーバーでは実現できず、ブラウザ側のJavaScriptとして
// 動き続ける必要があるので、ファイルの先頭で "use client" を宣言し、
// このファイルを「Client Component」に切り替えている。
//
// "use client" は「このファイル以降で使う関数コンポーネントを、
// ブラウザ側でも実行できるようにJSとして送ってください」という
// Next.jsへの合図であり、Reactそのものの機能ではなく
// Next.js（正確にはReact Server Components方式）が追加した仕組み。
//
// [初心者が間違えやすい点]
// ・"use client" を付けたら「サーバーで動かなくなる」わけではない。
//   最初の描画は依然としてサーバー側で行われ（SSR）、
//   その後ブラウザ側でJSが読み込まれて「再度動き出す」＝
//   状態を持ったり、useEffectが走ったりできるようになる、という意味。
// ・"use client" は「ファイル単位」の宣言。このファイルをimportして
//   使う側（page.tsxなど）まで自動的にClient Componentになるわけではない。
//   むしろ「Server ComponentがClient Componentを子として呼び出す」のが
//   Next.jsで推奨される基本パターン（今回のpage.tsx→Clockの関係がそれ）。

import { useEffect, useState } from "react";

export function Clock() {
  // [useState: Reactの「状態(state)」を持つための仕組み]
  // useState(初期値) は [現在の値, 値を更新する関数] のペアを返す。
  // ここでは「今何時か」という、時間とともに変わる値を保持している。
  //
  // [なぜ state を直接書き換えてはいけないのか]
  // 例えば `now.setHours(0)` のように now を直接いじっても、
  // 画面は更新されない。Reactは「stateを更新する関数(setNow)が
  // 呼ばれたこと」をトリガーにして再描画（re-render）を行う仕組みなので、
  // 値そのものをこっそり書き換えてもReactはそれに気づけない。
  // 必ず setNow(新しい値) という形で「新しいオブジェクト」を渡し、
  // Reactに「値が変わったので再描画して」と明示的に伝える必要がある。
  const [now, setNow] = useState(new Date());

  // [useEffect: 「描画そのもの」ではない副作用を扱う場所]
  // Reactのコンポーネントは本来「stateやpropsから見た目(JSX)を計算する」
  // ことに専念すべきもので、タイマーの開始のような「画面の外の世界」に
  // 影響する処理（副作用 = side effect）は分離して書く必要がある。
  // それを行うのがuseEffectで、「このコンポーネントが画面に表示された後に
  // 実行してほしい処理」をここに書く。
  useEffect(() => {
    // setInterval: 1000ms(1秒)ごとにコールバック関数を実行し続ける
    // ブラウザ標準のAPI（Reactの機能ではない）。
    // ここでは1秒ごとに setNow を呼び、stateを更新→再描画させている。
    const timerId = setInterval(() => {
      setNow(new Date());
    }, 1000);

    // [クリーンアップ関数が必要な理由]
    // useEffectの中でreturnした関数は「後片付け」として扱われ、
    // コンポーネントが画面から消える（unmountされる）タイミングで実行される。
    // もしこれを書かずにsetIntervalを放置すると、コンポーネントが
    // 消えた後もタイマーが動き続けてしまい（メモリリーク）、
    // 存在しない画面を更新しようとしてエラーの原因にもなる。
    // 「タイマーを開始したら、必ず片付け方も一緒に書く」がセット。
    return () => clearInterval(timerId);

    // [依存配列 [] の意味]
    // useEffectの第2引数（依存配列）は「この中の値が変わった時だけ
    // 上のeffectを再実行してください」という指定。
    // 空配列 [] を渡すと「何にも依存しない」＝
    // 「このコンポーネントが最初に画面に表示された時に1回だけ実行し、
    //   消える時に1回だけクリーンアップする」という意味になる。
    // もし依存配列を省略すると、再描画のたびに毎回effectが再実行され、
    // このケースでは「1秒ごとに新しいsetIntervalが増え続ける」という
    // バグ（タイマーの多重起動）になるので、[] を書き忘れないことが重要。
  }, []);

  return (
    <p>
      現在時刻: <time>{now.toLocaleTimeString("ja-JP")}</time>
    </p>
  );
}
