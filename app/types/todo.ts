// [TypeScriptの type とは]
// TypeScriptは「JavaScriptに型情報を追加した言語」で、
// この `type` は「このオブジェクトはこういう形をしている」という
// 設計図（型）に名前を付ける機能。ここでは「Todo1件」の形を定義している。
//
// [なぜ必要か]
// もし型が無ければ、Todoオブジェクトは実行するまで
// 「idがnumberなのかstringなのか」「doneというプロパティが本当にあるのか」
// が保証されない。タイプミス（例: `todo.dun`）や、
// プロパティの入れ忘れがあっても、実行するまで気づけない。
// 型を定義しておくと、エディタ上・コンパイル時点で
// 「そのプロパティは存在しません」とすぐ教えてもらえる。
//
// [type と interface の違い（今回どちらでも良いが type を選んだ理由）]
// interfaceは主に「オブジェクトの形」を拡張(extends)しながら定義するのに向き、
// typeは「オブジェクトの形」だけでなく、ユニオン型（A | B）のような
// より柔軟な型表現もできる。Todo程度のシンプルな形であればどちらでも書けるが、
// このプロジェクトでは一貫して type を使う方針にする。
//
// [各プロパティの意味と、後で使う理由]
// - id: 同じ文字列のTodoが複数あっても区別するための一意な値。
//   これは後で一覧表示するときに React の key として使う（Step 6で解説）。
// - text: Todoの内容そのもの（ユーザーがinputに入力する文字列）。
// - done: 完了したかどうかのフラグ。true/falseの2値なので boolean。
//   これを条件分岐（例: 完了なら打ち消し線を出す）に使う。
//
// [初心者が間違えやすい点]
// ・TypeScriptの型はあくまで「開発時のチェック」であり、
//   ビルド後のJavaScriptには型情報は一切残らない
//   （ブラウザで実行される段階ではただのJSオブジェクト）。
// ・`type Todo = {...}` は値ではなく「型」なので、
//   これ自体をimportしてconsole.logしたりすることはできない。
export type Todo = {
  id: number;
  text: string;
  done: boolean;
};
